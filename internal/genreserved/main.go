// Command genreserved generates reserved_gen.go from the spec's
// wgsl.reserved.plain (gpuweb/gpuweb, wgsl/wgsl.reserved.plain).
//
//	go run ./internal/genreserved <wgsl.reserved.plain> <spec-commit> > reserved_gen.go
package main

import (
	"bufio"
	"fmt"
	"os"
	"strings"
)

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: genreserved <wgsl.reserved.plain> <spec-commit>")
		os.Exit(2)
	}
	f, err := os.Open(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer f.Close()
	var words []string
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		if w := strings.TrimSpace(sc.Text()); w != "" {
			words = append(words, w)
		}
	}
	if err := sc.Err(); err != nil || len(words) == 0 {
		fmt.Fprintln(os.Stderr, "no words read", err)
		os.Exit(1)
	}
	fmt.Println("// Code generated by internal/genreserved from wgsl.reserved.plain at gpuweb/gpuweb", os.Args[2]+"; DO NOT EDIT.")
	fmt.Println()
	fmt.Println("package wgsl")
	fmt.Println()
	fmt.Println("var reservedWords = []string{")
	for _, w := range words {
		fmt.Printf("\t%q,\n", w)
	}
	fmt.Println("}")
}
