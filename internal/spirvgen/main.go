// Command spirvgen writes spirv/ops_gen.go: the numeric values of the SPIR-V
// instructions and of the enumerants the emitter uses, read from the Khronos
// grammar (SPIRV-Headers, include/spirv/unified1/spirv.core.grammar.json) rather
// than typed by hand, since a wrong number does not crash: it is another
// instruction.
//
//	go run ./internal/spirvgen -grammar <SPIRV-Headers>/include/spirv/unified1/spirv.core.grammar.json > spirv/ops_gen.go
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"strconv"
)

type grammar struct {
	Magic        string `json:"magic_number"`
	MajorV       int    `json:"major_version"`
	MinorV       int    `json:"minor_version"`
	Revision     int    `json:"revision"`
	Instructions []struct {
		Name   string `json:"opname"`
		Opcode int    `json:"opcode"`
	} `json:"instructions"`
	Kinds []struct {
		Category   string `json:"category"`
		Kind       string `json:"kind"`
		Enumerants []struct {
			Name  string `json:"enumerant"`
			Value any    `json:"value"`
		} `json:"enumerants"`
	} `json:"operand_kinds"`
}

// kinds are the enumerations the emitter uses.
var kinds = []string{"Capability", "StorageClass", "Decoration", "BuiltIn", "ExecutionModel", "ExecutionMode",
	"AddressingModel", "MemoryModel", "FunctionControl", "SelectionControl", "LoopControl"}

func main() {
	path := flag.String("grammar", "", "spirv.core.grammar.json")
	flag.Parse()
	b, err := os.ReadFile(*path)
	if err != nil {
		fail(err)
	}
	var g grammar
	if err := json.Unmarshal(b, &g); err != nil {
		fail(err)
	}
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by internal/spirvgen from spirv.core.grammar.json (SPIR-V %d.%d revision %d); DO NOT EDIT.\n\n", g.MajorV, g.MinorV, g.Revision)
	out.WriteString("package spirv\n\n")
	fmt.Fprintf(&out, "// Magic is the first word of every module.\nconst Magic = %s\n\n", g.Magic)
	out.WriteString("// Instruction opcodes.\nconst (\n")
	for _, in := range g.Instructions {
		fmt.Fprintf(&out, "\t%s = %d\n", in.Name, in.Opcode)
	}
	out.WriteString(")\n")
	for _, want := range kinds {
		found := false
		for _, k := range g.Kinds {
			if k.Kind != want {
				continue
			}
			found = true
			fmt.Fprintf(&out, "\n// %s enumerants.\nconst (\n", want)
			seen := map[string]bool{}
			for _, e := range k.Enumerants {
				var v uint64
				switch x := e.Value.(type) {
				case float64:
					v = uint64(x)
				case string:
					n, err := strconv.ParseUint(x, 0, 32)
					if err != nil {
						fail(err)
					}
					v = n
				}
				name := want + e.Name
				if seen[name] {
					continue // aliases of one value
				}
				seen[name] = true
				fmt.Fprintf(&out, "\t%s = %d\n", name, v)
			}
			out.WriteString(")\n")
		}
		if !found {
			fail(fmt.Errorf("no operand kind %s in the grammar", want))
		}
	}
	src, err := format.Source(out.Bytes())
	if err != nil {
		fail(err)
	}
	os.Stdout.Write(src)
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
